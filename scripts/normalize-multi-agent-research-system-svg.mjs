import {createHash} from 'node:crypto';
import {readFile, writeFile} from 'node:fs/promises';

import {
  collectDrawioPairValidation,
  collectXmlVisibleCopy,
  parseXml,
  xmlElements,
} from '../.codex/skills/creating-drawio-architecture-diagrams/scripts/xml-visible-copy.mjs';

const SVG_NAMESPACE = 'http://www.w3.org/2000/svg';
const [drawioPath, rawPath, outputPath] = process.argv.slice(2);
if (!drawioPath || !rawPath || !outputPath) {
  throw new Error(
    'usage: normalize-multi-agent-research-system-svg.mjs <source.drawio> <raw.svg> <published.svg>',
  );
}

const sha256 = (contents) => createHash('sha256').update(contents).digest('hex');
const sortedAttributes = (element) =>
  [...element.attributes].sort(([left], [right]) => left.localeCompare(right));
const cellSignatures = (root) => xmlElements(root, 'mxCell', '').map((cell) => ({
  attributes: sortedAttributes(cell),
  geometry: xmlElements(cell, 'mxGeometry', '').map(sortedAttributes),
}));
const visibleTexts = (inventory) => inventory.records.map(({text}) => text).sort();
const equal = (left, right) => JSON.stringify(left) === JSON.stringify(right);
const fail = (message) => {
  throw new Error(`multi-agent research SVG normalization failed: ${message}`);
};

const drawio = await readFile(drawioPath, 'utf8');
const raw = await readFile(rawPath, 'utf8');
const sourceSha256 = sha256(drawio);
const rawSha256 = sha256(raw);
const doctype = raw.match(/<!DOCTYPE svg PUBLIC "-\/\/W3C\/\/DTD SVG 1\.1\/\/EN" "http:\/\/www\.w3\.org\/Graphics\/SVG\/1\.1\/DTD\/svg11\.dtd">\s*/u);
if (!doctype) fail('raw artifact is not a diagrams.net SVG 1.1 export');
const rawWithoutDoctype = raw.replace(doctype[0], '');
const publishedPayload = rawWithoutDoctype.replace(
  /^<\?xml version="1\.0" encoding="UTF-8"\?>\s*<!-- Do not edit this file with editors other than draw\.io -->\s*/u,
  '',
);
if (!publishedPayload.startsWith('<svg ')) {
  fail('raw artifact preamble drifted from the diagrams.net export contract');
}

const sourceParsed = parseXml(drawio, drawioPath);
const rawParsed = parseXml(rawWithoutDoctype, rawPath);
if (sourceParsed.root.localName !== 'mxfile' || sourceParsed.root.namespace !== '') {
  fail('committed source is not a Draw.io mxfile');
}
if (rawParsed.root.localName !== 'svg' || rawParsed.root.namespace !== SVG_NAMESPACE) {
  fail('raw artifact is not an SVG');
}
const rawRoot = rawParsed.root;
if (!(rawRoot.attributes.get('id') ?? '').startsWith('ge-svg-')) {
  fail('raw artifact is missing its diagrams.net export identity');
}
if (
  rawRoot.attributes.get('width') !== '1764px'
  || rawRoot.attributes.get('height') !== '1894px'
  || rawRoot.attributes.get('viewBox') !== '0 0 1764 1894'
) {
  fail('raw export dimensions drifted from the reviewed 800px layout');
}
if (xmlElements(rawRoot, 'foreignObject', SVG_NAMESPACE).length !== 0) {
  fail('raw export must use portable SVG text, not foreignObject rendering');
}

const embedded = rawRoot.attributes.get('content');
if (!embedded) fail('raw export does not include a source copy');
const embeddedParsed = parseXml(embedded, `${rawPath}#content`);
if (!equal(cellSignatures(sourceParsed.root), cellSignatures(embeddedParsed.root))) {
  fail('embedded source copy does not exactly match committed cells and geometry');
}

const sourceCells = xmlElements(sourceParsed.root, 'mxCell', '');
const renderedGroups = xmlElements(rawRoot, 'g', SVG_NAMESPACE)
  .filter((element) => element.attributes.has('data-cell-id'));
if (renderedGroups.length !== sourceCells.length) {
  fail('rendered source-cell group count drifted');
}
const sourceIds = sourceCells.map((cell) => cell.attributes.get('id')).sort();
const renderedIds = renderedGroups.map((group) => group.attributes.get('data-cell-id')).sort();
if (!equal(sourceIds, renderedIds)) fail('rendered source-cell identity drifted');

const sourceVisible = collectDrawioPairValidation(sourceParsed, drawioPath);
const rawVisible = collectXmlVisibleCopy(rawParsed, rawPath, 'svg');
if (!equal(visibleTexts(sourceVisible), visibleTexts(rawVisible))) {
  fail('raw visible labels do not exactly match source labels');
}
if (xmlElements(rawRoot, 'text', SVG_NAMESPACE).length !== sourceVisible.records.length) {
  fail('raw text-node inventory drifted');
}

const rawRootTag = publishedPayload.match(/<svg\b[^>]*>/u)?.[0];
if (!rawRootTag) fail('cannot locate the raw SVG root tag');
let publishedRootTag = rawRootTag
  .replace(/\swidth="[^"]*"/u, '')
  .replace(/\sheight="[^"]*"/u, '')
  .replace(/\sid="[^"]*"/u, '')
  .replace(/\scontent="[^"]*"/u, '')
  .replace(
    /\sstyle="[^"]*"/u,
    ' style="background:#fff;background-color:#fff;color-scheme:light"',
  )
  .replace(/>$/u, [
    ' role="img"',
    ' aria-labelledby="multi-agent-research-system-title multi-agent-research-system-desc"',
    ` data-source-sha256="${sourceSha256}"`,
    ` data-raw-sha256="${rawSha256}">`,
  ].join(''));

const metadata = [
  '<title id="multi-agent-research-system-title">Multi-agent research system reference architecture</title>',
  '<desc id="multi-agent-research-system-desc">A four-region reference design showing orchestration, bounded parallel research, evidence authority, citation verification, human review, recovery, abstention, and terminal decisions.</desc>',
].join('');
const published = publishedPayload.replace(rawRootTag, `${publishedRootTag}${metadata}`);
const publishedParsed = parseXml(published, outputPath);
const publishedRoot = publishedParsed.root;
if (publishedRoot.attributes.has('width') || publishedRoot.attributes.has('height')) {
  fail('published root retained fixed dimensions');
}
if (publishedRoot.attributes.has('content')) fail('published root retained its source copy');
const publishedVisible = collectXmlVisibleCopy(publishedParsed, outputPath, 'svg');
if (!equal(visibleTexts(rawVisible), visibleTexts(publishedVisible))) {
  fail('published visible labels drifted during normalization');
}

await writeFile(outputPath, published, 'utf8');
console.log(
  `Normalized multi-agent research SVG: source ${sourceSha256}, raw ${rawSha256}, ${sourceCells.length} cells, ${sourceVisible.records.length} labels`,
);
